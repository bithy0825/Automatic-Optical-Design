# 按 d 线折射率升序排列，保证 GA 变异在特征空间中的语义稳定。
_SORTED = sorted(_SELLMEIER_DATA, key=lambda r: r[-2])

_SELLMEIER_NAMES: tuple[str, ...] = tuple(r[0] for r in _SORTED)

# 波长单位换算：λ(μm²) = λ(nm)² × 1e-6（Sellmeier 公式输入为 μm²）。
_NM_PER_UM2 = 1e-6


class SellmeierMaterialDatabase(MaterialDatabase):
    """Sellmeier 色散材料数据库（六系数公式，(nd, vd) 特征空间变异）。"""

    kind = term.SELLMEIER
    _NAMES: ClassVar[tuple[str, ...]] = _SELLMEIER_NAMES

    coeffs: torch.Tensor  # 以下均为 __init__ 注册的 buffer
    nd: torch.Tensor
    vd: torch.Tensor
    features: torch.Tensor

    def __init__(self) -> None:
        super().__init__()
        coeffs = torch.tensor([r[1:7] for r in _SORTED])
        nd = torch.tensor([r[7] for r in _SORTED])
        vd = torch.tensor([r[8] for r in _SORTED])
        nd_mean, nd_std = nd.mean(), nd.std()
        vd_mean, vd_std = vd.mean(), vd.std()
        features = torch.stack(
            ((nd - nd_mean) / nd_std, (vd - vd_mean) / vd_std), dim=-1
        )
        self.register_buffer("coeffs", coeffs, persistent=False)
        self.register_buffer("nd", nd, persistent=False)
        self.register_buffer("vd", vd, persistent=False)
        self.register_buffer("features", features, persistent=False)

    @property
    def names(self) -> tuple[str, ...]:
        return self._NAMES

    def forward(
        self, indices: SystemLongScalar, wavelength: RayFloatScalar
    ) -> RayFloatScalar:
        coeffs = self.coeffs.index_select(0, indices)
        coeffs = coeffs.view(
            indices.shape[0], *([1] * (wavelength.ndim - 1)), 6
        )  # (P, 1, 1, 1, 6)

        bc = coeffs[..., :3]  # (P, 1, 1, 1, 3)
        cc = coeffs[..., 3:]  # (P, 1, 1, 1, 3)

        w2 = wavelength.square().mul(_NM_PER_UM2).unsqueeze(-1)
        n2 = bc.mul(w2).div(w2.sub(cc)).sum(dim=-1).add(1)

        return n2.sqrt()

    def mutate(
        self,
        indices: SystemLongScalar,
        std: float,
        generator: torch.Generator | None = None,
    ) -> SystemLongScalar:
        """在 (nd, vd) 归一化特征空间中扰动 ``indices``，吸附到最近玻璃。"""
        query = self.features.index_select(0, indices)
        noise = torch.randn(
            query.shape, device=query.device, dtype=query.dtype, generator=generator
        )
        query = query.add(noise.mul(std))
        return torch.cdist(query, self.features).argmin(dim=-1)
